import type { Metadata, Viewport } from "next";
import { Poppins } from "next/font/google";
import "./globals.css";
import { ClerkProvider } from "@clerk/nextjs";
import { cookies } from "next/headers";
import { auth } from "@clerk/nextjs/server";
import { mergeGuestCart } from "@/actions/cart";

const poppins = Poppins({
  weight: ['400','500', '600'],
  subsets: ['latin'],
  display: 'swap',
  preload: false, // wyłącza preload
});

 
export const viewport: Viewport = {
  width: 'device-width',
  initialScale: 1,
  maximumScale: 1,
  userScalable: false,
  // Also supported but less commonly used
  // interactiveWidget: 'resizes-visual',
}
export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {

  const { userId } = await auth()
  const cookieStore = await cookies()

  const guestId = cookieStore.get('guest_id')?.value

  // merge tutaj — Server Component, Node.js runtime, bez problemu
  if (userId && guestId) {
    await mergeGuestCart(guestId, userId)
    // usunięcie cookie obsłuż przez action lub response header
  }
  return (
    <ClerkProvider>      
      <html lang="en">
        <body
          className={`${poppins.className} antialiased overflow-x-hidden`}
        >
            {children}
        </body>
      </html>
    </ClerkProvider>
  );
}
